"""Phase-3 per-cell statistical significance of condition vs baseline.

For each (condition, benchmark, data, instr) cell, run three significance
tests so a reader can pick whichever assumption set matches their claim:

  one_sample_p : One-sample t-test of the condition's per-seed accuracies
                 against baseline_mean as a fixed null. Multi-seed
                 conditions only (NaN for 1-seed conditions). Tightest test
                 against seed-to-seed reproducibility noise — the same
                 noise floor the conclusion_flips.tsv ±0.01 buffer guards
                 against.

  welch_p      : Welch's two-sample t-test on (seed, template) observations:
                 condition's 6 (multi-seed) or 2 (single-seed) obs vs
                 baseline's 2 obs (1 seed × 2 templates). Captures seed
                 AND template variance; low power on 1-seed cells but
                 returns a number for every cell.

  prop_z_p     : Binomial proportion z-test on per-example outcomes
                 pooled across seeds × templates. n_cond_total =
                 n_examples × n_seeds × n_templates; same for baseline.
                 Highest power (treats every example as an independent
                 trial), but OVERESTIMATES significance because cond and
                 baseline evaluate the same test set — a paired test
                 (McNemar's) on per-example outcomes would be tighter.
                 Use for directional evidence, not paper-grade claims.

The TSV also includes seed_sigma_pp (std across seeds, with templates
averaged within each seed), which lets a reader compute their own
threshold (e.g. 2σ_seed) per cell.

Output: significance.tsv at PHASE3_ANALYSIS_TABLES_DIR (default
        /tmp/phase3_analysis_output/), picked up by
        upload_analysis_tables.py for the standard HF upload.

Input: phase3/analysis/refined-tables/vs_baseline_cells.tsv on HF
       (the canonical per-cell delta TSV, regenerated by
       build_vs_baseline.py). Read direct from HF so this script is
       self-contained and doesn't depend on a local snapshot being
       built first.

Usage:
    python expedition-tiny-aya/evaluation/scripts/build_significance.py

    # Override the output directory:
    PHASE3_ANALYSIS_TABLES_DIR=/some/path python build_significance.py
"""
from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats as st

HF_REPO_ID = "legesher/language-decoded-experiments"
HF_REPO_TYPE = "dataset"
HF_VS_BASELINE_CELLS = "phase3/analysis/refined-tables/vs_baseline_cells.tsv"

OUT_DIR = Path(os.environ.get("PHASE3_ANALYSIS_TABLES_DIR",
                              "/tmp/phase3_analysis_output"))
OUT_FILE = OUT_DIR / "significance.tsv"

# Per-benchmark example counts (constant per cell across all conditions).
# These match the multilingual test-set sizes shipped with each benchmark.
N_EXAMPLES = {"sib200": 204, "xnli": 2505, "csqa": 1000, "belebele": 900}

BENCH_ORDER = ["sib200", "xnli", "csqa", "belebele"]


def load_cells() -> pd.DataFrame:
    """Download vs_baseline_cells.tsv from HF and coerce delta columns to float."""
    from huggingface_hub import hf_hub_download

    cached = hf_hub_download(
        repo_id=HF_REPO_ID,
        repo_type=HF_REPO_TYPE,
        filename=HF_VS_BASELINE_CELLS,
    )
    df = pd.read_csv(cached, sep="\t")
    for c in ("delta_orig", "delta_rep"):
        if df[c].dtype == object:
            df[c] = df[c].str.replace("+", "", regex=False).astype(float)
    return df


def compute_row(cond: str, benchmark: str, data: str, instr: str,
                cond_obs: np.ndarray, base_obs: np.ndarray,
                per_seed_vals: np.ndarray, n_per_example: int) -> dict:
    cond_mean = float(cond_obs.mean())
    base_mean = float(base_obs.mean())
    delta = cond_mean - base_mean

    # (1) One-sample t-test on per-seed values vs baseline_mean
    if len(per_seed_vals) >= 2:
        t1, p1 = st.ttest_1samp(per_seed_vals, popmean=base_mean)
        os_df = len(per_seed_vals) - 1
    else:
        t1, p1, os_df = float("nan"), float("nan"), 0

    # (2) Welch's two-sample t-test on (seed, template) observations
    if len(cond_obs) >= 2 and len(base_obs) >= 2:
        t2, p2 = st.ttest_ind(cond_obs, base_obs, equal_var=False)
        s1, s2 = cond_obs.var(ddof=1), base_obs.var(ddof=1)
        n1, n2 = len(cond_obs), len(base_obs)
        if s1 == 0 and s2 == 0:
            welch_df = float("inf")
        else:
            welch_df = ((s1 / n1 + s2 / n2) ** 2 /
                        ((s1 / n1) ** 2 / (n1 - 1) + (s2 / n2) ** 2 / (n2 - 1)))
    else:
        t2, p2, welch_df = float("nan"), float("nan"), float("nan")

    # (3) Binomial proportion z-test pooled across seeds × templates
    #
    # n_correct is derived directly from cond_obs.sum() × n_per_example
    # rather than from (mean × total), which would round-trip through an
    # intermediate division. The two forms are algebraically identical, but
    # the .sum()-then-multiply path skips a float division (cond_obs.sum() /
    # len(cond_obs)) and the subsequent re-multiplication, avoiding FP error
    # that could nudge counts by 1 near threshold p-values. Each entry in
    # cond_obs is already an accuracy proportion (correct / n_per_example
    # for one (seed, template) cell), so cond_obs.sum() × n_per_example
    # gives the integer total successes across all observations.
    n_cond_total = n_per_example * len(cond_obs)
    n_base_total = n_per_example * len(base_obs)
    n_cond_correct = int(round(float(cond_obs.sum()) * n_per_example))
    n_base_correct = int(round(float(base_obs.sum()) * n_per_example))
    p_pool = (n_cond_correct + n_base_correct) / (n_cond_total + n_base_total)
    se = np.sqrt(p_pool * (1 - p_pool) * (1 / n_cond_total + 1 / n_base_total))
    if se > 0:
        z = delta / se
        p_z = 2 * (1 - st.norm.cdf(abs(z)))
    else:
        z, p_z = float("nan"), float("nan")

    seed_sigma = float(per_seed_vals.std(ddof=1)) if len(per_seed_vals) > 1 else float("nan")

    # Missing numeric values are emitted as np.nan (not the empty string)
    # so that pandas keeps the columns float-dtyped. to_csv renders NaN as
    # empty by default, so the TSV display is identical to the old code.
    # Keeping float dtype matters for downstream comparisons (the
    # significance-marker lambdas below) and for re-reading the TSV into
    # pandas without object-dtype surprises.
    def _round_or_nan(x: float, ndigits: int) -> float:
        return round(x, ndigits) if not pd.isna(x) else float("nan")

    return {
        "condition": cond,
        "benchmark": benchmark,
        "data": data,
        "instr": instr,
        "n_seeds": len(per_seed_vals),
        "n_examples_cond": n_cond_total,
        "n_examples_base": n_base_total,
        "baseline_acc": _round_or_nan(base_mean, 4),
        "cond_acc": _round_or_nan(cond_mean, 4),
        "delta_pp": _round_or_nan(delta * 100, 2),
        "seed_sigma_pp": _round_or_nan(seed_sigma * 100, 2),
        "one_sample_t": _round_or_nan(t1, 3),
        "one_sample_df": os_df,
        "one_sample_p": _round_or_nan(p1, 5),
        "welch_t": _round_or_nan(t2, 3),
        "welch_df": _round_or_nan(welch_df, 2),
        "welch_p": _round_or_nan(p2, 5),
        "z_prop": _round_or_nan(z, 3),
        "prop_z_p": _round_or_nan(p_z, 5),
    }


def main() -> None:
    df = load_cells()
    rows = []
    for cond in sorted(df.condition.unique()):
        if cond == "baseline":
            continue
        cond_df = df[df.condition == cond]
        for benchmark in BENCH_ORDER:
            n_ex = N_EXAMPLES[benchmark]
            cond_b = cond_df[cond_df.benchmark == benchmark]
            for instr in cond_b.instr.unique():
                for data in cond_b[cond_b.instr == instr].data.unique():
                    cell = cond_b[(cond_b.data == data) & (cond_b.instr == instr)]
                    if len(cell) == 0:
                        continue
                    cond_obs = cell["cond_rep"].values
                    base_obs = cell.drop_duplicates(subset="template")["baseline_rep"].values
                    per_seed = cell.groupby("seed")["cond_rep"].mean().values
                    rows.append(compute_row(
                        cond, benchmark, data, instr,
                        cond_obs, base_obs, per_seed, n_ex,
                    ))

    out = pd.DataFrame(rows)
    n_comparisons = len(out)
    bonferroni_threshold = 0.05 / n_comparisons
    # Significance markers follow academic-stats convention:
    #   *   p < 0.05   (uncorrected)
    #   **  p < 0.01   (uncorrected)
    #   *** p < Bonferroni-adjusted (family-wise error 0.05; tightest)
    # We compute both columns rather than a single "best marker" column so a
    # reader can choose their preferred correction without reverse-engineering
    # the p-value back out of the marker. NaN p-values (no test possible)
    # render to an empty marker via pd.notna; comparing NaN < threshold
    # returns False which would also work, but pd.notna is explicit.
    out["sig_uncorrected_prop_z"] = out["prop_z_p"].apply(
        lambda p: "**" if pd.notna(p) and p < 0.01
        else ("*" if pd.notna(p) and p < 0.05 else "")
    )
    out["sig_bonferroni_prop_z"] = out["prop_z_p"].apply(
        lambda p: "***" if pd.notna(p) and p < bonferroni_threshold else ""
    )

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out.to_csv(OUT_FILE, sep="\t", index=False)
    print(f"Wrote {OUT_FILE}  ({len(out)} cells)")
    print(f"Bonferroni threshold (n={n_comparisons}): p < {bonferroni_threshold:.2e}")
    print()
    print("Summary by benchmark:")
    summary = out.groupby("benchmark").apply(
        lambda g: pd.Series({
            "n_cells": len(g),
            "n_sig_05_prop_z": (g["prop_z_p"] < 0.05).sum(),
            "n_sig_bonferroni_prop_z": (g["prop_z_p"] < bonferroni_threshold).sum(),
            "n_sig_one_sample_05": (g["one_sample_p"] < 0.05).sum(),
        }),
        include_groups=False,
    )
    print(summary.to_string())


if __name__ == "__main__":
    main()
